// The Reels Container's server. POST /render {html, duracao, arquivos?: [{nome, base64}]} → video/mp4.
// `arquivos`: the composition's images and music, once each (the HTML references them by name). One render at a time
// (the Worker sends one request per instance); each stage's time goes in the x-tempo-ms header. No internet: HyperFrames
// and Chrome are already in the image and are called by their installed path.
import http from 'node:http';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';

const APP = path.dirname(new URL(import.meta.url).pathname);
const GSAP = path.join(APP, 'node_modules/gsap/dist/gsap.min.js');
const HYPERFRAMES = path.join(APP, 'node_modules/.bin/hyperframes');
const MAX_BODY = 40 * 1024 * 1024;
const DEADLINE_MS = 6 * 60 * 1000;          // a stuck render (Chrome or FFmpeg) is killed
const MAX_LOG = 64 * 1024;
// Only simple names, generated by the Worker (a1.png, a2.svg, musica.mp3, voz.webm): no paths.
const NAME = /^[a-z0-9]{1,16}\.(png|jpe?g|svg|webp|mp3|m4a|webm|ogg|wav|flac|aac)$/;
let busy = false;

function run(cmd, args, cwd) {
  return new Promise((ok, failure) => {
    const p = spawn(cmd, args, { cwd, env: process.env, detached: true });
    let output = '';
    const join = (d) => { output = (output + d).slice(-MAX_LOG); };
    p.stdout.on('data', join);
    p.stderr.on('data', join);
    const deadline = setTimeout(() => {
      try { process.kill(-p.pid, 'SIGKILL'); } catch { p.kill('SIGKILL'); }
      failure(Object.assign(new Error(`render ran past ${DEADLINE_MS / 1000}s and was stopped`), { status: 504 }));
    }, DEADLINE_MS);
    p.on('error', (e) => { clearTimeout(deadline); failure(e); });
    p.on('close', (code) => {
      clearTimeout(deadline);
      if (code === 0) ok(output); else failure(new Error(`${cmd} exited with ${code}: ${output.slice(-2000)}`));
    });
  });
}

async function readBody(req) {
  const parts = [];
  let total = 0;
  for await (const p of req) {
    total += p.length;
    if (total > MAX_BODY) throw Object.assign(new Error('body too large'), { status: 413 });
    parts.push(p);
  }
  return JSON.parse(Buffer.concat(parts).toString('utf8'));
}

async function render(request) {
  const t0 = Date.now();
  if (typeof request.html !== 'string' || !request.html.includes('data-composition-id')) throw Object.assign(new Error('html: HyperFrames composition'), { status: 400 });
  const files = Array.isArray(request.arquivos) ? request.arquivos : [];
  for (const a of files) {
    if (typeof a?.nome !== 'string' || !NAME.test(a.nome) || typeof a.base64 !== 'string') throw Object.assign(new Error(`invalid file: ${String(a?.nome).slice(0, 40)}`), { status: 400 });
  }
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'reels-'));
  try {
    await fs.writeFile(path.join(dir, 'index.html'), request.html);
    await fs.copyFile(GSAP, path.join(dir, 'gsap.min.js'));
    for (const a of files) await fs.writeFile(path.join(dir, a.nome), Buffer.from(a.base64, 'base64'));
    const output = path.join(dir, 'reels.mp4');
    const t1 = Date.now();
    await run(HYPERFRAMES, ['render', dir, '--output', output, '--fps', '30', '--quality', 'standard', '--quiet'], APP);
    const mp4 = await fs.readFile(output);
    return { mp4, tempo: { preparo: t1 - t0, render: Date.now() - t1 } };
  } finally {
    await fs.rm(dir, { recursive: true, force: true });
  }
}

http.createServer(async (req, res) => {
  try {
    if (req.method === 'GET' && req.url === '/saude') { res.writeHead(200, { 'content-type': 'application/json' }); return res.end('{"ok":true}'); }
    if (req.method !== 'POST' || req.url !== '/render') { res.writeHead(404); return res.end(); }
    if (busy) { res.writeHead(429, { 'content-type': 'application/json' }); return res.end('{"erro":"render em andamento"}'); }
    busy = true;
    try {
      const { mp4, tempo: time } = await render(await readBody(req));
      res.writeHead(200, { 'content-type': 'video/mp4', 'content-length': mp4.length, 'x-tempo-ms': JSON.stringify(time) });
      res.end(mp4);
    } finally {
      busy = false;
    }
  } catch (e) {
    res.writeHead(e.status ?? 500, { 'content-type': 'application/json' });
    res.end(JSON.stringify({ erro: String(e.message ?? e).slice(0, 2000) }));
  }
}).listen(8080, () => console.log('reels: ouvindo na 8080'));
