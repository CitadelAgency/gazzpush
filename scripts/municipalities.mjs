// Generates web/src/data/municipalities.ts (the IBGE list for the municipality search in "Create outlet").
// Source: the CSV from github.com/kelvins/municipios-brasileiros (IBGE codes), because the IBGE API did not answer from here.
// Usage: node scripts/municipalities.mjs <municipios.csv> <estados.csv>
import { readFileSync, writeFileSync } from "node:fs";

const [munCsv, ufCsv] = process.argv.slice(2);
const lines = (f) => readFileSync(f, "utf8").trim().split(/\r?\n/).slice(1).map((l) => l.split(","));
const uf = Object.fromEntries(lines(ufCsv).map(([code, acronym]) => [code, acronym]));
const muns = lines(munCsv)
  .map(([ibge, name, , , , codeUf]) => [ibge, name, uf[codeUf]])
  .sort((a, b) => a[1].localeCompare(b[1], "pt-BR"));
if (muns.length < 5500 || muns.some(([i, n, u]) => !/^\d{7}$/.test(i) || !n || !u)) throw new Error("lista incompleta");
writeFileSync("web/src/data/municipalities.ts",
  "// Generated by scripts/municipalities.mjs (do not edit). One line per municipality: IBGE code|name|UF.\n" +
  `export default ${JSON.stringify(muns.map((m) => m.join("|")).join("\n"))};\n`);
console.log(muns.length, "municipalities");
